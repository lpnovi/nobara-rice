#!/usr/bin/env bash
# backup.sh — collect the known rice files from this machine into the repo.
#
# READ-ONLY on the system: it only reads from $HOME (and optionally the rEFInd
# staging folder) and writes inside this repository. It never runs sudo.
#
# It does NOT copy whole config files. For KDE it extracts only the listed
# appearance keys, and it replaces personal paths and disk UUIDs with placeholders.
#
# Usage: scripts/backup.sh [--dry-run]
#   REFIND_STAGING=/path/to/refind-work  (default: ~/refind-nobara-theme)
set -euo pipefail

REPO=$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)
CFG=${XDG_CONFIG_HOME:-$HOME/.config}
DATA=${XDG_DATA_HOME:-$HOME/.local/share}
REFIND_STAGING=${REFIND_STAGING:-$HOME/refind-nobara-theme}
DRY=0; [[ ${1:-} == --dry-run ]] && DRY=1

say()  { printf '\033[1;35m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m  !\033[0m %s\n' "$*" >&2; }
run()  { if (( DRY )); then echo "  [dry-run] $*"; else "$@"; fi; }

# Mirror a directory into the repo. Only ever deletes inside $REPO.
mirror() { # src dst [rsync args...]
  local src=$1 dst=$2; shift 2
  [[ -d $src ]] || { warn "missing $src (skipped)"; return 0; }
  [[ $dst == "$REPO"/* ]] || { echo "refusing to write outside repo: $dst"; exit 1; }
  run mkdir -p "$dst"
  run rsync -a --delete --exclude='*.kate-swp' --exclude='*~' --exclude='*.backup' \
      --exclude='*.bak*' --exclude='backup_*' "$@" "$src"/ "$dst"/
  echo "  $src -> ${dst#"$REPO"/}"
}

copy() { # src dst [mode]
  [[ -e $1 ]] || { warn "missing $1 (skipped)"; return 0; }
  run install -D -m "${3:-644}" "$1" "$2"; echo "  $1 -> ${2#"$REPO"/}"
}

# --- KDE: write an INI fragment containing only selected keys ----------------
# spec lines: "Group/SubGroup|key1 key2 ..."  ('/' separates nested groups)
fragment() { # rcfile out spec...
  local rc=$1 out=$2; shift 2
  local tmp; tmp=$(mktemp)
  for spec in "$@"; do
    local grp=${spec%%|*} keys=${spec#*|} gargs=() header="" v k
    IFS=/ read -ra parts <<<"$grp"
    for p in "${parts[@]}"; do gargs+=(--group "$p"); header+="[$p]"; done
    local lines=""
    for k in $keys; do
      v=$(kreadconfig6 --file "$rc" "${gargs[@]}" --key "$k" 2>/dev/null || true)
      [[ -n $v ]] && lines+="$k=$v"$'\n'
    done
    [[ -n $lines ]] && printf '%s\n%s\n' "$header" "$lines" >>"$tmp"
  done
  sanitize_paths "$tmp"
  if (( DRY )); then echo "  [dry-run] fragment $rc -> ${out#"$REPO"/}"; rm -f "$tmp"; return; fi
  mkdir -p "$(dirname "$out")"
  { echo "# Generated by scripts/backup.sh from ~/.config/$rc — only rice-related keys."
    echo "# Applied key-by-key with kwriteconfig6 by ./install.sh (other keys untouched)."
    echo; cat "$tmp"; } >"$out"
  rm -f "$tmp"; echo "  ~/.config/$rc -> ${out#"$REPO"/}"
}

# Replace wallpaper/home paths with placeholders the installer understands.
sanitize_paths() { # file (in place)
  sed -i -E \
    -e "s#file://$HOME/[^\"]*/([^/\"]+\.(jpg|jpeg|png|webp))#file://@WALLPAPER_DIR@/\1#g" \
    -e "s#$HOME#@HOME@#g" "$1"
}

# Replace disk/partition UUIDs with stable placeholders (order of appearance).
sanitize_uuids() { # in out
  awk '
    { line=$0; out="";
      while (match(line, /root=UUID=[0-9a-fA-F-]{36}/)) {
        out=out substr(line,1,RSTART-1) "root=UUID=@ROOT_UUID@"; line=substr(line,RSTART+RLENGTH) }
      line=out line; out="";
      while (match(line, /[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}/)) {
        u=tolower(substr(line,RSTART,RLENGTH)); if (!(u in id)) id[u]=++n
        out=out substr(line,1,RSTART-1) "@UUID_" id[u] "@"; line=substr(line,RSTART+RLENGTH) }
      print out line }' "$1" >"$2"
}

(( DRY )) && say "DRY RUN — nothing will be written"
cd "$REPO"
run mkdir -p assets refind/src refind/config

say "KDE config fragments"
fragment kdeglobals "$REPO/kde/config/kdeglobals.ini" \
  "General|font fixed menuFont smallestReadableFont toolBarFont XftAntialias XftHintStyle XftSubPixel TerminalApplication TerminalService" \
  "Icons|Theme" \
  "KDE|AnimationDurationFactor widgetStyle contrast frameContrast" \
  "WM|activeFont"
fragment kwinrc "$REPO/kde/config/kwinrc.ini" \
  "KDE|AnimationDurationFactor" \
  "NightColor|Active NightTemperature" \
  "Plugins|blurEnabled kwin6_effect_rippleEnabled local_quicktile_glideEnabled magiclampEnabled wobblywindowsEnabled translucencyEnabled scaleEnabled squashEnabled shakecursorEnabled kwin_gesturesEnabled ghostty-geometryEnabled kwin4_effect_shapecornersEnabled" \
  "Round-Corners|Size InactiveCornerRadius UseSquircleShape Squircleness DisableRoundMaximize DisableRoundTile DisableRoundFullScreen" \
  "Effect-overview|BorderActivate" \
  "TouchEdges|Top" \
  "org.kde.kdecoration2|library theme BorderSize BorderSizeAuto ButtonsOnLeft ButtonsOnRight"
fragment breezerc "$REPO/kde/config/breezerc.ini" \
  "Common|OutlineCloseButton OutlineEnabled OutlineIntensity RoundedCorners ShadowSize" \
  "Windeco|ButtonSize TitleAlignment"
fragment plasmarc        "$REPO/kde/config/plasmarc.ini"        "Theme|name"
fragment kcminputrc      "$REPO/kde/config/kcminputrc.ini"      "Mouse|cursorTheme cursorSize"
fragment ksplashrc       "$REPO/kde/config/ksplashrc.ini"       "KSplash|Engine Theme"
fragment kscreenlockerrc "$REPO/kde/config/kscreenlockerrc.ini" "Greeter/Wallpaper/org.kde.image/General|Image"
# Wallpaper images are not in the repo; point the lock screen at a neutral placeholder name.
run sed -i -E 's#^Image=file://@WALLPAPER_DIR@/.*#Image=file://@WALLPAPER_DIR@/lockscreen.jpg#' "$REPO/kde/config/kscreenlockerrc.ini"

say "Plasma Style, splash, KWin scripts/effects"
style=$(kreadconfig6 --file plasmarc --group Theme --key name)
if [[ -d $DATA/plasma/desktoptheme/$style ]]; then
  mirror "$DATA/plasma/desktoptheme/$style" "$REPO/kde/plasma-style/$style"
  copy "$DATA/plasma/desktoptheme-backups/$style/gen.py" "$REPO/kde/plasma-style/tools/gen.py"
elif [[ -d /usr/share/plasma/desktoptheme/$style ]]; then
  # A distro-provided style (stock Nobara on the source laptop). Vendored because
  # CachyOS/Arch does not ship it.
  mirror "/usr/share/plasma/desktoptheme/$style" "$REPO/kde/plasma-style/$style"
else warn "Plasma Style '$style' not found (nothing to copy)"; fi
if [[ -d $DATA/plasma/desktoptheme/Nobara-Enhanced && $style != Nobara-Enhanced ]]; then
  mirror "$DATA/plasma/desktoptheme/Nobara-Enhanced" "$REPO/kde/plasma-style/Nobara-Enhanced"
fi

# The live splash package keeps whatever ID it has locally; the repo always stores it
# under the neutral ID below (metadata.json in the repo is maintained by hand).
SPLASH_ID=nobara-enhanced.splash
splash=$(kreadconfig6 --file ksplashrc --group KSplash --key Theme)
if [[ -f $DATA/plasma/look-and-feel/$splash/contents/splash/Splash.qml ]]; then
  copy "$DATA/plasma/look-and-feel/$splash/contents/splash/Splash.qml" \
       "$REPO/kde/splash/$SPLASH_ID/contents/splash/Splash.qml"
  run sed -i "s/^Theme=.*/Theme=$SPLASH_ID/" "$REPO/kde/config/ksplashrc.ini"
fi

# Only KWin packages that are enabled in kwinrc [Plugins]
for kind in scripts effects; do
  for d in "$DATA/kwin/$kind"/*/; do
    [[ -f $d/metadata.json ]] || continue
    id=$(basename "$d")
    [[ $(kreadconfig6 --file kwinrc --group Plugins --key "${id}Enabled") == true ]] || continue
    mirror "${d%/}" "$REPO/kde/kwin/$kind/$id" --exclude=LICENSE --exclude=UPSTREAM.md --exclude=local-changes.diff --exclude=README.md
  done
done
copy "$HOME/.local/bin/ghostty-geometry-sync"             "$REPO/kde/kwin/scripts/ghostty-geometry-sync/ghostty-geometry-sync" 755
copy "$CFG/systemd/user/ghostty-geometry-sync.service"   "$REPO/kde/kwin/scripts/ghostty-geometry-sync/ghostty-geometry-sync.service"

say "Color scheme + Kvantum application theme"
scheme=$(kreadconfig6 --file kdeglobals --group General --key ColorScheme)
copy "$DATA/color-schemes/$scheme.colors" "$REPO/kde/color-schemes/$scheme.colors"
copy "$CFG/Kvantum/kvantum.kvconfig" "$REPO/kde/kvantum/kvantum.kvconfig"
kv=$(kreadconfig6 --file "$CFG/Kvantum/kvantum.kvconfig" --group General --key theme 2>/dev/null || true)
[[ -n $kv && -d $CFG/Kvantum/$kv ]] && mirror "$CFG/Kvantum/$kv" "$REPO/kde/kvantum/$kv"
APPTHEME=$DATA/nobara-enhanced-apptheme
# gen_kvantum.py in the repo has KVANTUM_OUT support; flag live edits instead of overwriting it.
strip_out() { grep -vE 'KVANTUM_OUT|^OUT = |^# Keep in sync|^# \(installed to' "$1"; }
if [[ -f $APPTHEME/gen_kvantum.py ]] && ! diff -q <(strip_out "$APPTHEME/gen_kvantum.py") \
     <(strip_out "$REPO/kde/kvantum/gen_kvantum.py") >/dev/null; then
  warn "live gen_kvantum.py differs from kde/kvantum/gen_kvantum.py — merge by hand"
fi
mirror "$APPTHEME/base" "$REPO/kde/kvantum/base"

say "Plasmoids (user-made + vendored third-party) and the Kickoff fork sources"
for id in local.lpnovi.taskiconhover org.kde.plasma.windowtitlereborn; do
  mirror "$DATA/plasma/plasmoids/$id" "$REPO/kde/plasmoids/$id"
done
LAUNCHER=$DATA/nobara-enhanced-launcher
for d in upstream-6.7.4 nobara; do mirror "$LAUNCHER/$d" "$REPO/kde/launcher/$d" --exclude=__pycache__; done
copy "$LAUNCHER/swap-launcher.py" "$REPO/kde/launcher/swap-launcher.py" 755
# Reference diff, regenerated from a scratch build so it carries no local paths.
if (( ! DRY )); then
  t=$(mktemp -d); cp -r "$REPO/kde/launcher/upstream-6.7.4" "$t/"
  KICKOFF_OUT=$t/local.lpnovi.kickoff python3 "$REPO/kde/launcher/build.py" >/dev/null
  (cd "$t" && diff -ruN -x config.qml -x main.xml -x metadata.json -x Messages.sh -x CMakeLists.txt -x code \
     upstream-6.7.4 local.lpnovi.kickoff/contents/ui | sed -E 's/\t[0-9]{4}-[0-9-]+ [0-9:.]+ [-+][0-9]{4}$//') \
     >"$REPO/kde/launcher/nobara-changes.diff" || true
  rm -rf "$t" "$REPO/kde/launcher/__pycache__"; echo "  kde/launcher/nobara-changes.diff regenerated"
fi
# build.py in the repo has KICKOFF_OUT support; flag live edits instead of overwriting it.
if [[ -f $LAUNCHER/build.py ]] && ! diff -q <(grep -v KICKOFF_OUT "$LAUNCHER/build.py" | grep -v '^OUT = ') \
     <(grep -v KICKOFF_OUT "$REPO/kde/launcher/build.py" | grep -v '^OUT = ') >/dev/null; then
  warn "live launcher build.py differs from kde/launcher/build.py — merge by hand"
fi

say "Kickoff (app launcher) icon"
# Wallpapers are intentionally NOT collected (third-party game art); see wallpapers/README.md.
icon=$(grep -m1 -oP '^icon=\K/.*' "$CFG/plasma-org.kde.plasma.desktop-appletsrc" || true)
if [[ -n $icon && -f $icon ]]; then
  # Source may be WebP with a .png name; store a real PNG.
  run magick "$icon" -strip "PNG32:$REPO/assets/nobara-logo.png"; echo "  $icon -> assets/nobara-logo.png"
fi
# Keep the packaged splash complete: Splash.qml loads images/logo.png
copy "$REPO/assets/nobara-logo.png" "$REPO/kde/splash/$SPLASH_ID/contents/splash/images/logo.png"

say "Ghostty"
copy "$CFG/ghostty/config.ghostty" "$REPO/ghostty/config.ghostty"
for t in "$CFG"/ghostty/themes/*; do copy "$t" "$REPO/ghostty/themes/$(basename "$t")"; done

say "InputActions gestures"
copy "$CFG/inputactions/config.yaml" "$REPO/extras/inputactions/config.yaml"

say "rEFInd theme (from $REFIND_STAGING)"
theme=$REFIND_STAGING/nobara-purple
if [[ -d $theme ]]; then
  mirror "$theme" "$REPO/refind/theme/nobara-purple"
  for f in build-theme.sh build-icons-v2.sh; do
    [[ -f $REFIND_STAGING/$f ]] || continue
    (( DRY )) && { echo "  [dry-run] $f"; continue; }
    sed -e "s#$HOME/Downloads/Nobara Logo no background.png#\${NOBARA_LOGO:-../../assets/nobara-logo.png}#" \
        -e "s#$HOME#\$HOME#g" "$REFIND_STAGING/$f" >"$REPO/refind/src/$f"
    echo "  $f -> refind/src/$f (paths sanitized)"
  done
  for f in refind.conf refind_linux.conf; do
    [[ -f $REFIND_STAGING/$f ]] || continue
    (( DRY )) || { sanitize_uuids "$REFIND_STAGING/$f" "$REPO/refind/config/$f.template"
                   sed -i -E 's/^# [A-Za-z]+ recovery FAT partition/# Vendor recovery FAT partition/' "$REPO/refind/config/$f.template"; }
    echo "  $f -> refind/config/$f.template (UUIDs replaced)"
  done
else
  warn "no rEFInd staging folder; theme not refreshed (the live ESP needs root to read)"
fi

say "Privacy check"
user=$(id -un)
if grep -rIlE "$HOME|/home/$user|@(gmail|proton|outlook)\." "$REPO" --exclude-dir=.git \
     --exclude=backup.sh --exclude=privacy-check.sh 2>/dev/null; then
  warn "the files above mention your home path or an e-mail address — review before committing"
else echo "  no home paths or e-mail addresses found"; fi
say "Done. Review with: git -C \"$REPO\" status && git -C \"$REPO\" diff"
